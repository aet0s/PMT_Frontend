import { defineConfig, loadEnv } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import fs from 'fs';
import path from 'path';

function cspPlugin(apiUrl, isProd) {
  return {
    name: 'html-csp-transform',
    transformIndexHtml(html) {
      let connectSrc = "'self'";
      let imgSrc = "'self' data: blob:";

      if (apiUrl) {
        try {
          const parsed = new URL(apiUrl);
          const origin = parsed.origin;
          const wsProtocol = parsed.protocol === 'https:' ? 'wss:' : 'ws:';
          const wsOrigin = `${wsProtocol}//${parsed.host}`;
          connectSrc += ` ${origin} ${wsOrigin}`;
          imgSrc += ` ${origin}`;
        } catch {
          connectSrc += ` ${apiUrl}`;
        }
      }

      if (isProd) {
        if (!connectSrc.includes('https:')) connectSrc += ' https: wss:';
        if (!imgSrc.includes('https:')) imgSrc += ' https:';
      } else {
        connectSrc += ' http: ws: https: wss:';
        imgSrc += ' http: https:';
      }

      // Allow Firebase and FCM origins
      connectSrc += ' https://fcm.googleapis.com https://firebaseinstallations.googleapis.com https://fcmregistrations.googleapis.com';
      const workerSrc = "'self' blob:";
      const frameSrc = `'self' blob: data: https://view.officeapps.live.com https://*.officeapps.live.com https://docs.google.com`;
      const objectSrc = `'self' blob:`;
      const csp = `default-src 'self'; script-src 'self' 'unsafe-inline' https://www.gstatic.com; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com data:; img-src ${imgSrc} data: blob:; connect-src ${connectSrc} blob:; worker-src ${workerSrc}; frame-src ${frameSrc}; object-src ${objectSrc}; base-uri 'self';`;
      const metaTag = `<meta http-equiv="Content-Security-Policy" content="${csp}" />`;

      return html.replace('<!-- CSP_META -->', metaTag);
    }
  };
}

function firebaseSwPlugin(env) {
  return {
    name: 'generate-firebase-sw',
    buildStart() {
      const publicDir = path.resolve(__dirname, 'public');
      if (!fs.existsSync(publicDir)) {
        fs.mkdirSync(publicDir, { recursive: true });
      }
      const swPath = path.join(publicDir, 'firebase-messaging-sw.js');
      const firebaseConfig = {
        apiKey: env.VITE_FIREBASE_API_KEY || '',
        authDomain: env.VITE_FIREBASE_AUTH_DOMAIN || '',
        projectId: env.VITE_FIREBASE_PROJECT_ID || '',
        messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID || '',
        appId: env.VITE_FIREBASE_APP_ID || ''
      };

      const swContent = `// Auto-generated by Vite on build / dev start - DO NOT EDIT MANUALLY
/* eslint-disable no-undef */
importScripts('https://www.gstatic.com/firebasejs/10.14.0/firebase-app-compat.js');
importScripts('https://www.gstatic.com/firebasejs/10.14.0/firebase-messaging-compat.js');

const firebaseConfig = ${JSON.stringify(firebaseConfig, null, 2)};

if (firebaseConfig.apiKey && firebaseConfig.projectId && firebaseConfig.messagingSenderId) {
  try {
    firebase.initializeApp(firebaseConfig);
    const messaging = firebase.messaging();

    messaging.onBackgroundMessage((payload) => {
      const notif = payload.notification || {};
      const data = payload.data || {};
      const title = notif.title || data.title || 'TaskFlow Notification';
      const body = notif.body || data.body || '';
      const icon = notif.icon || data.icon || '/icons/icon-192.png';
      const badge = notif.badge || data.badge || '/icons/icon-192.png';
      const tag = notif.tag || data.tag || 'taskflow-push';

      return self.registration.showNotification(title, {
        body,
        icon,
        badge,
        tag,
        data: {
          url: data.url || '/',
          notification_id: data.notification_id,
          event_type: data.event_type
        }
      });
    });
  } catch (err) {
    console.warn('[SW] Firebase messaging init failed:', err);
  }
}

// Notification Click: Focus existing tab and navigate to data.url, or open new window
self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const rawUrl = event.notification.data?.url || 
                 event.notification.data?.FCM_MSG?.data?.url || 
                 '/';
  const targetUrl = new URL(rawUrl, self.location.origin).href;

  event.waitUntil(
    clients.matchAll({ type: 'window', includeUncontrolled: true }).then((clientList) => {
      for (const client of clientList) {
        if ('focus' in client) {
          if ('navigate' in client) {
            client.navigate(targetUrl);
          }
          return client.focus();
        }
      }
      if (clients.openWindow) {
        return clients.openWindow(targetUrl);
      }
    })
  );
});

// Push subscription change handler
self.addEventListener('pushsubscriptionchange', (event) => {
  event.waitUntil(
    self.registration.pushManager.subscribe(event.oldSubscription ? event.oldSubscription.options : { userVisibleOnly: true })
      .then((subscription) => {
        return clients.matchAll({ type: 'window' }).then((clientList) => {
          clientList.forEach((client) => {
            client.postMessage({ type: 'PUSH_SUBSCRIPTION_CHANGED', subscription });
          });
        });
      })
      .catch((err) => {
        console.warn('[SW] pushsubscriptionchange failed:', err);
      })
  );
});
`;

      fs.writeFileSync(swPath, swContent, 'utf8');
    }
  };
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '');
  const apiTarget = 'http://127.0.0.1:5000';
  const isProd = mode === 'production';

  return {
    plugins: [
      react(),
      tailwindcss(),
      cspPlugin(apiTarget, isProd),
      firebaseSwPlugin(env)
    ],
    test: {
      globals: true,
      environment: 'jsdom',
      setupFiles: './src/test/setup.js'
    },
    server: {
      port: 5173,
      proxy: {
        '/api': {
          target: apiTarget,
          changeOrigin: true,
          secure: false
        },
        '/uploads': {
          target: apiTarget,
          changeOrigin: true,
          secure: false
        },
        '/socket.io': {
          target: apiTarget,
          changeOrigin: true,
          ws: true,
          secure: false
        }
      }
    }
  };
});
